/* ══════════════════════════════════════════════════════════════════════
   📑 区分（分類）と、商品の並び順の【親】　2026-09-09 ひろみさん指示

   ★なぜ1つのファイルにするのか
     統合マスタＮ（名簿・価格リスト）と、輸入・原価Ｅ（🔒原価データ）で
     商品の並びがズレていて、見間違うもとになっていました。
     ひろみさんの決めごと：
       「統合マスタと原価データの商品の並びは、常に一緒にしておく。
         合わせる先は【統合マスタ】。統合マスタで商品が増えていくから。」

     並び順を2か所に書くと、片方だけ直したときに必ずズレます
     （2026-09-09に、番号の計算が2か所にあってズレた事故を実際に起こしています）。
     だから【この1つのファイルだけ】に書きます。

   ★使う側
     master.html（統合マスタＮ）／ import.html（輸入・原価Ｅ）
     どちらも <script src="oos-kubun.js"></script> で読み込みます。

   ★この並びを変えるときは、ひろみさんに確認してください。
   ★このファイルを消さないでください。読み込みが消えると並びがバラバラに戻ります。
   ══════════════════════════════════════════════════════════════════════ */
(function (glob) {

  /* 区分の並び順。ここに書いた順に並びます。
     ここに無い区分（あとから作ったもの）は、うしろに足されます。 */
  var GROUP_ORDER = [
    'オルガニック', 'メメジック', 'シェフズブレンド', 'プリモフルット', 'ザイトゥーン', 'アグルミ',
    '唐辛子オイル', 'アルモニア',   /* ★2026-09-09 その他オイルから独立させた */
    'その他オイル',                /* 品番の頭は OIL-（カサアルバート・モンテ物産など） */
    'オイル以外輸入商品',           /* 品番の頭は ETC-（ザクロソースなど）。その他オイルの次 */
    'カップオイル',
    'セット',                      /* ★ギフト商品より前 */
    'ギフト商品',
    '備品-箱', '備品-バッグ', '備品-その他',
    'その他'
  ];

  /* 商品の一覧を、統合マスタと同じ並びにして返す。
     ・区分は上の GROUP_ORDER の順
     ・同じ区分の中は、商品マスタに入っている順（＝ひろみさんが登録した順）のまま
     ★元の配列は変えません（新しい配列を返します）。 */
  function sortProducts(products) {
    var list = (products || []).slice();
    var rank = {};
    GROUP_ORDER.forEach(function (g, i) { rank[g] = i; });
    var extra = GROUP_ORDER.length;      // 表に無い区分は、うしろへ（出てきた順）
    list.forEach(function (p) {
      var g = (p && p.group) || 'その他';
      if (rank[g] === undefined) { rank[g] = extra++; }
    });
    /* 登録順を覚えておく（同じ区分の中の順番を崩さないため） */
    var pos = new Map();
    list.forEach(function (p, i) { pos.set(p, i); });
    return list.sort(function (a, b) {
      var ga = rank[(a && a.group) || 'その他'], gb = rank[(b && b.group) || 'その他'];
      if (ga !== gb) return ga - gb;
      return pos.get(a) - pos.get(b);
    });
  }

  /* ══════════════════════════════════════════════════════════════════════
     🏷 商品管理番号（品番 ＋ バーコード下4桁）の【親】　★2026-09-16 ひろみさん指示
     ──────────────────────────────────────────────────────────────────────
     ひろみさん「3つ同じことをやっているのは、ちょっと事故が起きやすい」
     　　　　　「とにかくアプリと揃えて。ずれてたり、壊れたりしないようにしたい」

     2026-09-16 に実測したところ、この計算が【3つのアプリに書き写されて】いました。
     　・統合マスタＮ（master.html）… displaySkuCode
     　・受注Ａ（index.html）　　　　 … dispCodeOf ／ lineCodeHtmlA
     　・倉庫Ｄ（pickup.html）　　　　… dispCodeOf ／ lineBarcode4
     55商品で突き合わせたところ、そのときは【3つとも同じ答え・食いちがい0件】でしたが、
     どれか1つを直したときに、ほかが古いまま残る危険がずっと残ります。
     → この1か所だけに書きます。アプリは呼ぶだけにします。

     ★決めごと（変えるときはひろみさんに確認してください）
     　・番号 ＝ 品番 ＋ '-' ＋ バーコードの下4桁
     　・バーコードが無い／4桁に足りないときは【品番だけ】。ハイフンは出さない
     　　（2026-09-16 時点で55商品のうち24商品がこの形＝箱・紙袋・備品など）
     　・バーコードは 名簿の「バーコード」欄 → jan → barcode の順に見る
     　・数字と英字だけを見る（ハイフンや空白は取り除く）

     ★セット商品の番号（SET-下4桁-下4桁）は、ここではなく統合マスタＮの
     　mbSetKanriFrom が持っています（セットは在庫リストに出ないため）。

     ★GASだけは、このファイルを読めません（Googleのサーバーで動くため）。
     　GASには唯一のコピー（oosKanriBangou_）があり、
     　tests/test_kanri_bangou.js が【親とGASが同じ答えを出すか】を毎回くらべます。
     ══════════════════════════════════════════════════════════════════════ */

  /* 商品からバーコードを取り出す（名簿の「バーコード」欄が正）。無ければ '' */
  function barcodeOf(p) {
    if (!p) return '';
    var v = p['バーコード'];
    if (!v && p.extras) v = p.extras['バーコード'];
    if (!v) v = p.jan || p.barcode || '';
    return String(v || '').trim();
  }

  /* バーコードの下4桁。取れなければ ''（商品でも、文字そのものでも渡せます） */
  function shita4(x) {
    var s = (x && typeof x === 'object') ? barcodeOf(x) : String(x || '');
    var d = s.replace(/[^0-9A-Za-z]/g, '');
    return d.length >= 4 ? d.slice(-4) : '';
  }

  /* 商品管理番号＝品番＋バーコード下4桁。バーコードが無ければ品番だけ */
  function kanriBangou(p) {
    if (!p || !p.sku) return '';
    var t = shita4(p);
    return t ? (String(p.sku) + '-' + t) : String(p.sku);
  }

  glob.OOS_KUBUN = {
    ORDER: GROUP_ORDER,
    sortProducts: sortProducts,
    barcodeOf: barcodeOf,
    shita4: shita4,
    kanriBangou: kanriBangou
  };

})(typeof window !== 'undefined' ? window : globalThis);
