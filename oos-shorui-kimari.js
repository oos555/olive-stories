/* ══════════════════════════════════════════════════════════════════════════
   お客様にお渡しする書類の【決めごと】　oos-shorui-kimari.js
   2026-09-11 作成

   ══ ひろみさんへ ══════════════════════════════════════════════════════
   このファイルは【ひろみさんが読んで、直すところ】です。
   下の「必ず載るもの」の表と、送料・ピッキング手数料の金額を直せば、
   納品書・請求書にそのまま反映されます。プログラムの言葉は要りません。

   ★このファイルに書いたものが書類から消えると、
   　tests/test_shorui_kanarazu.js が必ず落ちます（Claudeが消せません）。
   ★Claudeへ：この表に勝手に足さない・勝手に消さない。
   　変えるときは、必ずひろみさんに聞いてから。
   ═══════════════════════════════════════════════════════════════════════

   ── なぜこのファイルが要るのか（2026-09-11 ひろみさんのお叱り）────────
     ひろみさん：「請求書からまたピックアップ料金と送料が抜けていた。
     　　　　　　どうして直しても直しても直しても、こうやって勝手に落とすの？」

     原因：これまで「金額が入っていれば行を出す」という作りでした。
     　　　受注Ａで手入力した注文には送料・手数料の金額が入らないので、
     　　　行ごと消えていました。「入れ忘れ」と同じに見えて気づけません。
     これから：【枠は必ず出す】。金額が0でも「無料」「別途」と書いて出します。
     　　　　　消えたら見張りが落ちます。
   ══════════════════════════════════════════════════════════════════════════ */
(function (root) {
  'use strict';

  /* ══════════════════════════════════════════════════════════════════
     ① 数字（金額）が載る書類　★ひろみさん決定（2026-09-11）
     ──────────────────────────────────────────────────────────────────
     ひろみさん：「受注出荷Ａで同梱する可能性がある書類がこれだけある、全部で6種類。
     　　　　　　パンフレットと、その他（自分で書く）以外は【全部数字が載る】」
     ★この6つが、受注Ａの「同梱する書類」で選べるものです。
     ★パンフレット と その他（自分で書く）には数字を載せません。
     ★Claudeへ：この一覧を勝手に減らさないこと。
     　「納品書だけなら金額を出さない」に戻さないでください（2026-09-11に変えました）。
     ══════════════════════════════════════════════════════════════════ */
  var SUJI_GA_NORU = [
    '納品書兼請求書',
    '納品書兼領収書',
    'RT発注伝票＋納品書',
    '納品書',
    '請求書',
    '領収書'
  ];
  /* 数字を載せないもの */
  var SUJI_NASHI = ['パンフレット', 'その他', 'なし'];

  /* ══════════════════════════════════════════════════════════════════
     ② 必ず載るもの（枠）
     　　上の6種類ぜんぶに、この2つの行を【消費税と同じように当たり前に】出します。
     　　金額が0でも、行は消しません（0なら「無料」「別途」と書きます）。
     ★ひろみさん決定（2026-09-11）。消さないでください。
     ══════════════════════════════════════════════════════════════════ */
  var KANARAZU = [
    /* ★2026-09-12 承認済みモック（第7版）の文言にそろえました。
       ★「倉庫ピッキング手数料」に戻さないでください。ひろみさんの言葉は「ピックアップ料金」です。 */
    { key: 'pickup', name: '倉庫ピックアップ料金（バラ出荷）', memo: 'バラ（単品・ケース割れ）のときだけ金額が入ります' },
    { key: 'soryo',  name: '送料',                             memo: 'お届け先の都道府県で決まります' }
  ];

  /* ══════════════════════════════════════════════════════════════════
     ② 送料（税込）　── 決めごとＳ（soryo.html）のとおり
     　　お届け先の都道府県で自動。ヤマト運輸＝県単位。
     　　2026-07-24 改定：北海道・沖縄県＝1,100／その他＝880（すべて税込）
     ★金額を直すときは、soryo.html と order.html の表も一緒に直してください。
     ══════════════════════════════════════════════════════════════════ */
  var SORYO_ZEIKOMI = { '北海道': 1100, '沖縄県': 1100, 'その他': 880 };

  /* ══════════════════════════════════════════════════════════════════
     ③ 倉庫ピッキング手数料（税抜）　── バラ（単品・ケース割れ）出荷のときだけ
     　　ひろみさん（2026-09-11）：
     　　　「一般の方にはピックアップ料金はサービスで無料。卸の人は必ずもらう。
     　　　　RTの場合は一回700円プラス消費税。
     　　　　そうじゃない卸の場合は、一回につき250円プラス消費税」
     ★送料は【税込】ですが、ピッキング手数料は【税抜】です（決めごとＳ）。
     　消費税10%を足し忘れると、卸で25円・RTで70円ぶん取りそこねます。
     ══════════════════════════════════════════════════════════════════ */
  var PICKUP_ZEINUKI = {
    rt: 700, rtgc: 700,                 /* RT・RTGC … 1回 700円＋消費税 */
    wholesale1: 250, wholesale2: 250,   /* 卸①・卸② … 1回 250円＋消費税 */
    general: 0                          /* 一般（定価）… サービスで無料 */
    /* ★バサラ（basara）と 特別提供価格（special）は、まだ決まっていません。
       いまは0（無料）です。もらうことになったら、ここに足してください。
       ★Claudeが勝手に足さないこと。 */
  };

  /* ══════════════════════════════════════════════════════════════════
     ④ 単位（本・缶・個）　★ひろみさん決定（2026-09-12）
     ──────────────────────────────────────────────────────────────────
     ひろみさん：「単位について　100ｍｌ、250ｍｌ、500ｍｌは 本
     　　　　　　750ｍｌ、2000ｍｌ、5000ｍｌは 缶　3000ｍｌは 個」
     　　　　　「単位は、アプリの方でもし間違っていたら人間が修正できるようにして」
     → 商品マスタの「単位」欄に書いてあれば【そちらが優先】します（人が直せます）。
     　 書いていなければ、下の表で容量から決めます。
     ★この表を勝手に増やさない・減らさないでください。
     ══════════════════════════════════════════════════════════════════ */
  var TANI_BY_ML = [
    { ml: 100,  tani: '本' },
    { ml: 250,  tani: '本' },
    { ml: 500,  tani: '本' },
    { ml: 750,  tani: '缶' },
    { ml: 2000, tani: '缶' },
    { ml: 3000, tani: '個' },
    { ml: 5000, tani: '缶' }
  ];
  var TANI_KITEI = '本';   /* どれにも当てはまらないときは「本」 */

  /* 商品名から容量（ml）を読み取る。250ml・2L・3L・5000ml など、いろいろな書き方に合わせます */
  function mlOf(p) {
    var n = String((p && (p.name || p.sku)) || '');
    var m = n.match(/(\d+(?:\.\d+)?)\s*(ml|ｍｌ|ML|mL)/);
    if (m) return Math.round(parseFloat(m[1]));
    m = n.match(/(\d+(?:\.\d+)?)\s*(L|l|Ｌ|ℓ|リットル)/);
    if (m) return Math.round(parseFloat(m[1]) * 1000);
    return null;
  }

  /* この商品の単位（本・缶・個）。★人が直した「単位」欄がいちばん強い */
  function taniOf(p) {
    var te = (p && p.extras && String(p.extras['単位'] || '').trim()) || '';
    if (te) return te;                      /* ★人が直したものを優先 */
    var ml = mlOf(p);
    if (ml != null) {
      for (var i = 0; i < TANI_BY_ML.length; i++) {
        if (TANI_BY_ML[i].ml === ml) return TANI_BY_ML[i].tani;
      }
    }
    return TANI_KITEI;
  }

  /* お届け先の住所・都道府県から、送料（税込）を出す */
  function soryoOf(jusho) {
    var s = String(jusho || '');
    if (/北海道/.test(s)) return { fee: SORYO_ZEIKOMI['北海道'], chiiki: '北海道' };
    if (/沖縄/.test(s))   return { fee: SORYO_ZEIKOMI['沖縄県'], chiiki: '沖縄県' };
    return { fee: SORYO_ZEIKOMI['その他'], chiiki: 'その他' };
  }

  /* 区分から、ピッキング手数料（税抜）を出す。バラが無いときは0 */
  function pickupOf(kubun, baraAri) {
    if (!baraAri) return 0;
    var t = (root.OOS_KAKAKU ? root.OOS_KAKAKU.normalizeType(kubun) : kubun) || 'general';
    var v = PICKUP_ZEINUKI[t];
    return (v == null) ? 0 : v;
  }

  /* この注文に「バラ（単品・ケース割れ）」があるか */
  function baraAriKa(o) {
    var lines = (o && o.lines) || [];
    for (var i = 0; i < lines.length; i++) {
      var l = lines[i];
      if (l && (Number(l.bottles) || 0) > 0) return true;   /* バラの本数が1以上 */
    }
    return false;
  }

  /* ══════════════════════════════════════════════════════════════════
     この書類に、上の「必ず載るもの」を出すか
     ──────────────────────────────────────────────────────────────────
     ★答え：【金額が出る書類なら、必ず出す】
     ひろみさん（2026-09-11）：
     　「納品書と請求書という言葉が入っているものに関しては、
     　　必ずピックアップ料金と送料の枠を入れといてください」
     　　例）納品書兼請求書／請求書兼領収書／納品書兼領収書
     はじめ「納品書と請求書の両方の言葉が入るか」で見ていましたが、
     　「請求書兼領収書」（納品書の言葉が無い）で枠が出ませんでした。
     金額が出る書類なら必ず、という形にしてあります（これがいちばん抜けません）。
     ★「両方の言葉が入るか」に戻さないでください。
     ══════════════════════════════════════════════════════════════════ */
  /* この書類に数字（金額）を載せるか。上の6種類なら載せます */
  function sujiGaNoruKa(shoruiMei) {
    var d = String(shoruiMei || '').trim();
    if (!d) return true;                      /* 空＝既定は 納品書兼請求書（数字あり） */
    for (var i = 0; i < SUJI_NASHI.length; i++) {
      if (d === SUJI_NASHI[i]) return false;  /* パンフレットだけ／その他だけ／なし */
    }
    for (var j = 0; j < SUJI_GA_NORU.length; j++) {
      if (d.indexOf(SUJI_GA_NORU[j]) >= 0) return true;
    }
    return false;
  }

  /* 必ず載るもの（ピッキング手数料・送料）の枠を出すか。
     ★数字が載る書類なら【いつでも出す】。ひろみさん：
     　「この6種類すべての書類に、毎回 倉庫ピックアップ料金と送料の枠は、
     　　消費税のように当たり前のように、まず枠を設けるようにして」 */
  function kanarazuDasuKa(shoruiMei) {
    return sujiGaNoruKa(shoruiMei);
  }

  root.OOS_SHORUI = {
    KANARAZU: KANARAZU,
    SORYO_ZEIKOMI: SORYO_ZEIKOMI,
    PICKUP_ZEINUKI: PICKUP_ZEINUKI,
    soryoOf: soryoOf,
    pickupOf: pickupOf,
    baraAriKa: baraAriKa,
    SUJI_GA_NORU: SUJI_GA_NORU,
    SUJI_NASHI: SUJI_NASHI,
    sujiGaNoruKa: sujiGaNoruKa,
    TANI_BY_ML: TANI_BY_ML,
    mlOf: mlOf,
    taniOf: taniOf,
    kanarazuDasuKa: kanarazuDasuKa
  };
})(typeof window !== 'undefined' ? window : globalThis);

if (typeof module !== 'undefined' && module.exports) { module.exports = (typeof window !== 'undefined' ? window : globalThis).OOS_SHORUI; }
