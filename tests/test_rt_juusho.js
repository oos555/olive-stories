/* ══════════════════════════════════════════════════════════════
   ⑦ 先祖返りの見張り（1行まるごとで見る形に戻っていないか）
   ══════════════════════════════════════════════════════════════ */
{
  const fn = H.cut(INDEX, 'parseRtSlip').replace(/\/\*[\s\S]*?\*\//g, '');
  ok('⑦1行見つけたら break、の形に戻っていない',
     /\{\s*addrRest\s*=\s*s;\s*break;\s*\}/.test(fn) === false,
     '（住所を1行で打ち切る書き方が戻っています）');
  ok('⑦1行を【ます目】に割ってから見ている',
     fn.indexOf('_masu') >= 0 && fn.indexOf("split('|')") >= 0,
     '（| で割らずに1行まるごと見る形に戻ると、番地の行ごと捨てられます）');
  ok('⑦1行まるごとを1つの文字にする書き方が無い',
     /top\[j\]\.replace\(\/\\\|\/g/.test(fn) === false,
     '（1行まるごとを1つの文字にすると、番地と伝票番号がくっついて捨てられます）');
  ok('⑦やめる合図（TEL・FAXなど）が決めてある', fn.indexOf('RT_ADDR_TOME') >= 0);
  ok('⑦住所の続きの合図が決めてある', fn.indexOf('RT_ADDR_TSUZUKI') >= 0);
  ok('⑦あて名から御中・〒・都道府県のます目を外している', fn.indexOf('RT_ATENA_JYOGAI') >= 0);
  /* ★都道府県の二重書きは、③（本物の横浜ベイコート倶楽部の伝票）で
     　実際に動かして確かめています。書き方を文字で探す見張りは足しません
     　（張りぼて点検①を増やさないため）。 */
}

