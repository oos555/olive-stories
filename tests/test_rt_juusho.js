     私は「住所は1行ずつ下に続く」と思い込んで見張りを書きました。
     見張りは通りました。でも【本物の伝票はその形ではありませんでした】。
     本物（380789／サンクチュアリコート高山）はこうです：

       ㈱オリーブオイル・ストーリーズ(2926) | サンクチュアリコート高山
       御中 | 〒506-0055 | 岐阜県
       T9012801020687
       高山市上岡本町
