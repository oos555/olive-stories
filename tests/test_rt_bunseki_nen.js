/* ══════════════════════════════════════════════════════════════════════
   📅 RT台帳の分析を【年で分ける】
   2026-09-15 指示 → 2026-09-16 納品

   ★ひろみさんの言葉
     「合計が、入れた伝票全部を足してるんだけど、**年で分けてほしい**。
     　シェフが変わると全然変わるので」
     「**RT全体のトータルは1個あってほしい**」
     「それぞれのホテルの施設の合計3年分合計4年分合計っていうのは
     　**あんまり意味がない**」

   ★実データでの裏づけ
     ラグーナベイコート：2022年 745,327 → 2025年 297,600（減）
     東京ベイコート　　：2022年 144,886 → 2025年 2,070,480（14倍）
     足すと、この正反対の動きが消えます。

   ★いちばん大事な見張り（⑤）
     前の分析タブには、**私が手で書いた読み物と数字**が埋め込まれていました
     （「5年でいちばん大きな出来事は…」「2022年の年商の46%はアイバリック2L」など）。
     台帳から計算した数字ではないので、伝票を足しても変わらない＝必ず合わなくなります。
     ひろみさんの「数字が間違わないこと」に真っ向から反します。
     **画面に出る数字は、すべて台帳（SALES）から計算すること。**
   ══════════════════════════════════════════════════════════════════════ */
const fs = require('fs');
const vm = require('vm');
const path = require('path');
const H = require('./harness');

const LIVE = path.join(__dirname, '..');
const SRC = fs.readFileSync(path.join(LIVE, 'rt_chef_daicho.html'), 'utf8');

const title = '📅 RT台帳の分析を年で分ける（2026-09-16）';
let pass = 0, fail = 0;
const fails = [];
function ok(name, cond, detail){
  if (cond) { pass++; return; }
  fail++; fails.push('        ' + name + (detail ? '  ' + detail : ''));
}
function eq(name, got, want){
  ok(name, got === want, '（出た答え：' + JSON.stringify(got) + '／ほしい答え：' + JSON.stringify(want) + '）');
}

/* ── 本物の関数を、作り物の台帳で動かす砂場 ── */
function sunaba(sales){
  const el = { innerHTML: '' };
  const ctx = vm.createContext({
    console: console, Math: Math, Number: Number, String: String,
    Object: Object, Array: Array, Date: Date,
    SALES: sales,
    document: { getElementById: function(id){ return id === 'ai-body' ? el : null; } },
    esc: function(s){ return String(s == null ? '' : s)
      .replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;').replace(/"/g,'&quot;'); }
  });
  ctx.window = ctx; ctx.globalThis = ctx;
  vm.runInContext(SRC.match(/var SIZE_RE = [^\n]*\n/)[0], ctx);
  ['brandOf','aiBars','aiShukei','aiFacOfYear','aiNaiTsuki','aiNaiTsukiBun','aiSetNen','renderAI']
    .forEach(function(n){ vm.runInContext(H.cut(SRC, n), ctx); });
  vm.runInContext('var AI_NEN = "";', ctx);
  return { ctx: ctx, el: el,
           run: function(code){ return vm.runInContext(code, ctx); } };
}

/* 作り物の台帳（施設, 商品, 数量, 単位, 納品日, 金額） */
const DAI = [
  ['ラグーナベイコート倶楽部','シンフォニア500ml',24,'本','2022-01-08',100000],
  ['ラグーナベイコート倶楽部','シンフォニア500ml',10,'本','2022-06-08', 50000],
  ['ラグーナベイコート倶楽部','オルガニック100ml',10,'本','2024-03-08', 30000],
  ['東京ベイコート倶楽部','オルガニック100ml',6,'本','2022-01-07',  10000],
  ['東京ベイコート倶楽部','オルガニック100ml',60,'本','2024-05-07', 400000],
  ['サンクチュアリコート高山','メメジック500ml',12,'本','2024-04-07', 60000],
  /* ★金額がまだ入っていない行（本数だけ入れてある） */
  ['サンクチュアリコート高山','オルガニック2L',6,'缶','2024-04-07', 0]
];

/* ══════════════════════════════════════════════════════════════
   ① 数えかた（金額なしの行を、合計に混ぜない）
   ══════════════════════════════════════════════════════════════ */
{
  const S = sunaba(DAI).run('aiShukei()');
  eq('①RT全体のトータル', S.zen, 650000);
  eq('①合計に入れた行の数', S.kensu, 6);
  eq('①金額がまだ入っていない行の数', S.kingakuNashi, 1);
  eq('①その年の金額なしの行の数', S.yrNashi['2024'], 1);
  eq('①年の一覧', S.nen.join(','), '2022,2024');
  eq('①年ごと 2022', S.yr['2022'], 160000);
  eq('①年ごと 2024', S.yr['2024'], 490000);
  eq('①施設×年 ラグーナ2022', S.facYr['ラグーナベイコート倶楽部']['2022'], 150000);
  eq('①施設×年 ラグーナ2024', S.facYr['ラグーナベイコート倶楽部']['2024'], 30000);
  eq('①金額なしの行は、施設の年にも足さない', S.facYr['サンクチュアリコート高山']['2024'], 60000);
}

/* ══════════════════════════════════════════════════════════════
   ② 画面：RT全体のトータルは【1つだけ】
   ══════════════════════════════════════════════════════════════ */
{
  const s = sunaba(DAI); s.run('renderAI()');
  const h = s.el.innerHTML;
  const kazu = (h.match(/RT全体のトータル/g) || []).length;
  eq('②「RT全体のトータル」は1か所だけ', kazu, 1);
  ok('②その数字が台帳の合計と同じ', h.indexOf('¥650,000') >= 0, '（¥650,000 が見つかりません）');
  ok('②金額がまだ入っていない行があることを、必ず言う',
     h.indexOf('金額がまだ入っていない行が 1行あります') >= 0);
}

/* ══════════════════════════════════════════════════════════════
   ③ 画面：施設ごと × 年の表（施設の全期間合計の列は作らない）
   ══════════════════════════════════════════════════════════════ */
{
  const s = sunaba(DAI); s.run('renderAI()');
  const h = s.el.innerHTML;
  const hyou = h.slice(h.indexOf('施設ごと'), h.indexOf('年を選んで見る'));
  ok('③表に年の見出しが並んでいる',
     hyou.indexOf('>2022年<') >= 0 && hyou.indexOf('>2024年<') >= 0);
  ok('③施設の「合計」の列を作っていない',
     hyou.indexOf('>合計<') < 0 && hyou.indexOf('>全期間<') < 0,
     '（ひろみさん「3年分合計・4年分合計はあんまり意味がない」）');
  ok('③ラグーナの2022と2024が別々に出ている',
     hyou.indexOf('¥150,000') >= 0 && hyou.indexOf('¥30,000') >= 0);
  ok('③東京ベイコートは「増えている」と出る（1万→40万）',
     /東京ベイコート倶楽部[\s\S]{0,600}?▲ 増えている/.test(hyou),
     '（出た表：' + hyou.replace(/<[^>]*>/g,' ').replace(/\s+/g,' ').slice(0,300) + '）');
  ok('③ラグーナは「減っている」と出る（15万→3万）',
     /ラグーナベイコート倶楽部[\s\S]{0,600}?▼ 減っている/.test(hyou));
  ok('③取引の大きい施設が上に来る（東京ベイコートがラグーナより上）',
     hyou.indexOf('東京ベイコート倶楽部') < hyou.indexOf('ラグーナベイコート倶楽部'));
}

/* ══════════════════════════════════════════════════════════════
   ④ 画面：年を選ぶボタンと、その年だけのオイル別・商品別
   ══════════════════════════════════════════════════════════════ */
{
  const s = sunaba(DAI); s.run('renderAI()');
  let h = s.el.innerHTML;
  ok('④年を選ぶボタンがある', h.indexOf("aiSetNen('2022')") >= 0 && h.indexOf("aiSetNen('2024')") >= 0);
  ok('④はじめは、いちばん新しい年を出す', h.indexOf('2024年の施設別') >= 0);
  ok('④その年に金額なしの行があれば、必ず言う',
     h.indexOf('2024年は、金額がまだ入っていない行が 1行あります') >= 0);
  /* 年を変えると中身が変わる */
  s.run("aiSetNen('2022')");
  h = s.el.innerHTML;
  ok('④年を押すと、その年に変わる', h.indexOf('2022年の施設別') >= 0 && h.indexOf('2024年の施設別') < 0);
  ok('④2022年には、2024年だけの施設が出てこない',
     h.slice(h.indexOf('2022年の施設別')).indexOf('サンクチュアリコート高山') < 0);
  ok('④オイル別も年で分かれている', h.indexOf('2022年のオイル別') >= 0);
  ok('④商品別も年で分かれている', h.indexOf('2022年の商品別') >= 0);
}

/* ══════════════════════════════════════════════════════════════
   ⑤ ★決め打ちの文章・数字を画面に書かない（いちばん大事）
   ══════════════════════════════════════════════════════════════ */
{
  const fn = H.cut(SRC, 'renderAI');
  const NG = ['5年でいちばん大きな出来事', 'アイバリック', '943,719', '4,090,954', '12,680,000',
              '最終更新：', '2023年（65枚）', '八瀬離宮に一度に90缶'];
  NG.forEach(function(w){
    ok('⑤決め打ちの文章・数字「' + w + '」が無い', fn.indexOf(w) < 0,
       '（台帳から計算していない数字は、伝票を足しても変わらず、必ず合わなくなります）');
  });
  ok('⑤画面の数字は台帳から数えている', fn.indexOf('aiShukei()') >= 0);
}

/* ══════════════════════════════════════════════════════════════
   ⑥ まだ台帳に入っていない年月を、台帳から計算して出す
   ══════════════════════════════════════════════════════════════ */
{
  const s = sunaba(DAI);
  const tsuki = { '2023-02':1, '2023-05':1, '2023-06':1, '2023-07':1, '2024-01':1 };
  s.ctx.__t = tsuki;
  const nai = s.run('aiNaiTsuki(__t)');
  ok('⑥2023-03 と 2023-04 が「入っていない」に出る',
     nai.indexOf('2023-03') >= 0 && nai.indexOf('2023-04') >= 0, '（出た答え：' + nai.join(' ') + '）');
  ok('⑥入っている月は出てこない', nai.indexOf('2023-02') < 0 && nai.indexOf('2024-01') < 0);
  s.ctx.__n = ['2023-01','2023-03','2023-04','2023-05','2023-06','2023-07','2023-08',
               '2023-09','2023-10','2023-11','2023-12','2023-02'];
  eq('⑥12か月ぜんぶ抜けていたら「まるごと12か月」と書く',
     s.run('aiNaiTsukiBun(__n)').join(''), '2023年（まるごと12か月）');
  s.ctx.__n2 = ['2025-01','2025-02','2025-09','2025-10','2025-11','2025-12'];
  eq('⑥続いている月はまとめて書く',
     s.run('aiNaiTsukiBun(__n2)').join(''), '2025年 1月〜2月・9月〜12月');
}

if (fail) {
  console.log('  ★ ' + title + ' PASS ' + pass + ' / FAIL ' + fail);
  fails.forEach(x => console.log(x));
  process.exitCode = 1;
} else {
  console.log('  ✅ ' + title + ' PASS ' + pass + ' / FAIL 0');
}
